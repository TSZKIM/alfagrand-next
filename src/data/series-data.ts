/**
 * Get series data by category slug + series slug
 */
export function getSeriesData(slug: string, series: string): SeriesData | undefined {
  return seriesDataMap[`${slug}/${series}`];
}

/**
 * Get all { slug, series } pairs for generateStaticParams
 */
export function getAllSeriesSlugs(): { slug: string; series: string }[] {
  return Object.keys(seriesDataMap).map((key) => {
    const [slug, ...rest] = key.split("/");
    return { slug, series: rest.join("/") };
  });
}
